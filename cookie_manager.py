"""Cookie storage for yt-dlp + ytmusicapi."""
from __future__ import annotations
import os, time
from pathlib import Path
from typing import Any, Dict, Optional

DATA_DIR = Path(os.environ.get("COOKIE_DIR", "/tmp/yt-stream-cookies"))
COOKIES_FILE = DATA_DIR / "cookies.txt"


class CookieManager:
    def __init__(self) -> None:
        DATA_DIR.mkdir(parents=True, exist_ok=True)

    def path(self) -> Optional[Path]:
        if COOKIES_FILE.exists() and COOKIES_FILE.stat().st_size > 50:
            return COOKIES_FILE
        for key in ("YTDLP_COOKIES", "COOKIES_PATH"):
            env = os.environ.get(key)
            if env and Path(env).exists():
                return Path(env)
        return None

    def status(self) -> Dict[str, Any]:
        p = self.path()
        if not p:
            return {"has_cookies": False, "path": None, "size": 0}
        st = p.stat()
        return {
            "has_cookies": True,
            "path": str(p),
            "size": st.st_size,
            "mtime": time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(st.st_mtime)),
        }

    def save_netscape(self, text: str) -> Path:
        text = (text or "").strip()
        if len(text) < 30:
            raise ValueError("Cookie file too short / empty")
        COOKIES_FILE.write_text(text, encoding="utf-8")
        return COOKIES_FILE

    def save_from_header(self, cookie_header: str) -> Path:
        cookie_header = (cookie_header or "").strip()
        if cookie_header.lower().startswith("cookie:"):
            cookie_header = cookie_header[7:].strip()
        pairs = [p.strip() for p in cookie_header.split(";") if p.strip() and "=" in p]
        if len(pairs) < 2:
            raise ValueError("No valid cookie pairs found — need at least SID / HSID etc.")
        exp = str(int(time.time()) + 3600 * 24 * 400)
        lines = [
            "# Netscape HTTP Cookie File",
            "# Generated by YT Stream API",
            "",
        ]
        for pair in pairs:
            name, _, value = pair.partition("=")
            name, value = name.strip(), value.strip()
            if not name:
                continue
            for domain in (".youtube.com", "youtube.com", ".google.com", ".youtube.com"):
                lines.append(f"{domain}\tTRUE\t/\tTRUE\t{exp}\t{name}\t{value}")
        COOKIES_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")
        return COOKIES_FILE

    def clear(self) -> None:
        if COOKIES_FILE.exists():
            COOKIES_FILE.unlink(missing_ok=True)
